const translations: Record<Locale, Record<TranslationKey, string>> = {ko, en};

export function detectPreferredLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const requested = new URLSearchParams(window.location.search).get('lang');
  if (requested === 'ko' || requested === 'en') return requested;
  let saved: string | null = null;
  try {
    saved = window.localStorage.getItem('heapscout.locale');
  } catch {
    // Browser storage can be unavailable in hardened privacy modes.
  }
  if (saved === 'ko' || saved === 'en') return saved;
  return window.navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  parameters: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    translations[locale][key],
  );
}

const errorTranslationKeys: Readonly<Record<string, TranslationKey>> = {
  FILE_PICKER_UNAVAILABLE: 'error.filePickerUnavailable',
  FILE_PICKER_BUSY: 'error.filePickerBusy',
  INVALID_REQUEST: 'error.invalidRequest',
  JOB_NOT_FOUND: 'error.jobNotFound',
  ANALYSIS_NOT_READY: 'error.analysisNotReady',
  ANALYSIS_CAPACITY_EXCEEDED: 'error.capacityExceeded',
  INVALID_HPROF: 'error.invalidHprof',
  ANALYSIS_FAILED: 'error.analysisFailed',
  NETWORK_ERROR: 'error.network',
  UNEXPECTED_ERROR: 'error.unexpected',
};

export function translateError(locale: Locale, error: AnalysisFailure): string {
  const key = errorTranslationKeys[error.code];
  return key ? translate(locale, key) : error.message;
}
